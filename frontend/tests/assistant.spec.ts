test('AI is opt-in and unavailable responses retain current filters', async ({ page }) => {
  await page.goto('/watchlist')
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Username', { exact: true }).fill(`ai_${Date.now()}`)
  await page.getByLabel('Password', { exact: true }).fill('a-long-private-test-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your watchlist', exact: true })).toBeVisible()
  await page.route('**/api/assistant/coverage', route => route.fulfill({json:{released_movies:10,with_runtime:10,with_language:10,ai_available:true}}))
  await page.goto('/recommendations')
  await expect(page.getByLabel('Interpret my request')).not.toBeChecked()
  await page.getByLabel('Genre', { exact: true }).selectOption('Science Fiction')
  await page.getByLabel('Interpret my request').check()
  let captured: Record<string, unknown> = {}
  await page.route('**/api/assistant/chat', async route => {
    captured = route.request().postDataJSON()
    await route.fulfill({json:{reply:'Request interpretation is temporarily unavailable. Your filters are unchanged.', filters:captured.filters, items:[], mode:'ai-unavailable', needs_clarification:true}})
  })
  await page.getByLabel('Message Movie Match').fill('Something with a sense of wonder')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByRole('log').getByText(/Request interpretation is temporarily unavailable/)).toBeVisible()
  expect(captured.use_ai).toBe(true)
  await expect(page.getByLabel('Genre', { exact: true })).toHaveValue('Science Fiction')
})
