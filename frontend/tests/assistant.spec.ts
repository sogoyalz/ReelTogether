import { expect, test } from '@playwright/test'

test('guest favourites, follow-up constraints, and different picks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/recommendations')
  await page.getByLabel('Favourite movies').fill('Chat Movie 00')
  await page.getByRole('button', { name: 'Add Chat Movie 00 (2020)' }).click()
  await page.getByLabel('Message Movie Match').fill('English science fiction under two hours')
  await page.getByRole('button', { name: 'Send message' }).click()
  const results = page.getByRole('region', { name: 'Recommended movies' })
  await expect(results).toBeVisible()
  await expect(results.getByRole('heading', { name: 'Chat Movie 00', exact: true })).toHaveCount(0)
  await expect(results.getByText('Shares Science Fiction with Chat Movie 00.').first()).toBeVisible()
  await page.getByLabel('Message Movie Match').fill('No horror')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByText('Excluding: Horror')).toBeVisible()
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('English')
  await expect(page.getByLabel('Maximum runtime (minutes)')).toHaveValue('119')
  await expect(results.getByRole('heading', { name: 'Chat Movie 02', exact: true })).toHaveCount(0)
  const first = await results.locator('h3').allTextContents()
  await page.getByRole('button', { name: 'Show more', exact: true }).click()
  await expect(results.getByRole('heading', { name: 'Chat Movie 08', exact: true })).toBeVisible()
  expect((await results.locator('h3').allTextContents()).every(title => !first.includes(title))).toBeTruthy()
  expect(errors).toEqual([])
})

