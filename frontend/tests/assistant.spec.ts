test('account taste survives reload and dismissal can be undone', async ({ page }) => {
  await page.goto('/watchlist')
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Username', { exact: true }).fill(`taste_${Date.now()}`)
  await page.getByLabel('Password', { exact: true }).fill('a-long-private-test-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your watchlist', exact: true })).toBeVisible()
  await page.goto('/recommendations')
  await page.getByLabel('Favourite movies').fill('Chat Movie 00')
  await page.getByRole('button', { name: 'Add Chat Movie 00 (2020)' }).click()
  await expect(page.getByRole('button', { name: 'Remove favourite Chat Movie 00' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remove favourite Chat Movie 00' })).toBeVisible()
  await page.getByRole('button', { name: 'Find my movies' }).click()
  await page.getByRole('button', { name: 'Dismiss Chat Movie 01', exact: true }).click()
  await page.getByText('Dismissed movies', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Undo dismissal: Chat Movie 01' })).toBeVisible()
  await page.reload()
  await page.getByText('Dismissed movies', { exact: true }).click()
  await page.getByRole('button', { name: 'Undo dismissal: Chat Movie 01' }).click()
  await expect(page.getByText('Dismissed movies', { exact: true })).toHaveCount(0)
})

